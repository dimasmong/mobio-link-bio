export type Language = "en" | "id";

export const DEFAULT_LANGUAGE: Language = "en";
export const SUPPORTED_LANGUAGES: Language[] = ["en", "id"];

/**
 * Validates and safely normalizes a language string.
 * Defaults to DEFAULT_LANGUAGE ("en").
 */
export function parseLanguage(val?: string | null): Language {
	if (!val) return DEFAULT_LANGUAGE;
	const clean = val.toLowerCase().trim();
	if (clean === "id" || clean.startsWith("id-")) return "id";
	if (clean === "en" || clean.startsWith("en-")) return "en";
	return DEFAULT_LANGUAGE;
}

/**
 * Parses language preference from an HTTP Cookie header.
 */
export function parseLanguageCookie(cookieHeader?: string | null): Language {
	if (!cookieHeader) return DEFAULT_LANGUAGE;
	const match = cookieHeader.match(/(?:^|;\s*)mobio_lang=([a-zA-Z-]+)/);
	if (match && match[1]) {
		return parseLanguage(match[1]);
	}
	return DEFAULT_LANGUAGE;
}

/**
 * Synchronizes language preference to both document.cookie and localStorage.
 */
export function setLanguagePreference(lang: Language) {
	if (typeof document !== "undefined") {
		document.cookie = `mobio_lang=${lang}; path=/; max-age=31536000; SameSite=Lax`;
		document.documentElement.lang = lang;
	}
	if (typeof localStorage !== "undefined") {
		try {
			localStorage.setItem("mobio_lang", lang);
		} catch {
			// Ignore localStorage errors (e.g. private browsing mode)
		}
	}
}

/**
 * Retrieves localized text with fallback logic:
 * 1. Checks localized[lang] (trimmed).
 * 2. If empty, falls back to the other language (en <-> id).
 * 3. If still empty, falls back to the provided fallback string.
 */
export function getLocalizedText(
	localized?: { en?: string | null; id?: string | null } | null,
	lang: Language = DEFAULT_LANGUAGE,
	fallback = ""
): string {
	if (!localized) return fallback;
	const primary = (localized[lang] || "").trim();
	if (primary) return primary;
	const fallbackLang = lang === "en" ? "id" : "en";
	const secondary = (localized[fallbackLang] || "").trim();
	if (secondary) return secondary;
	return fallback;
}

